-- ===== permisos =====
-- La app no tiene login, así que entra con la llave anon (que es pública porque
-- viaja en el HTML). Estas políticas le dan lectura y escritura completas.
-- IMPORTANTE: cualquiera que tenga la URL de la app puede leer y escribir estos
-- datos. Si eso no es aceptable, hay que agregar login de Supabase y cambiar
-- 'anon' por 'authenticated' en las políticas de abajo.
alter table clients      enable row level security;
alter table products     enable row level security;
alter table trucks       enable row level security;
alter table destinations enable row level security;
alter table truck_loads  enable row level security;

create policy anon_all on clients      for all to anon using (true) with check (true);
create policy anon_all on products     for all to anon using (true) with check (true);
create policy anon_all on trucks       for all to anon using (true) with check (true);
create policy anon_all on destinations for all to anon using (true) with check (true);
create policy anon_all on truck_loads  for all to anon using (true) with check (true);
