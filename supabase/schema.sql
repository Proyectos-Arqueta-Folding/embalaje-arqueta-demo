drop table if exists truck_loads cascade;
drop table if exists products cascade;
drop table if exists clients cascade;
drop table if exists destinations cascade;
drop table if exists trucks cascade;

create table clients (
  id          bigint generated by default as identity primary key,
  name        text not null
);

create table products (
  id                  bigint generated by default as identity primary key,
  name                text not null,
  sku                 text,
  client_id           bigint references clients(id) on delete set null,
  boxes_per_corrugado integer,
  cantidad_por_cama   integer,
  estiba              integer,
  unit_price          numeric
);
create index on products (client_id);

create table trucks (
  id               bigint generated by default as identity primary key,
  name             text not null,
  pallet_capacity  integer not null,
  freight_category text
);

create table destinations (
  id              bigint generated by default as identity primary key,
  name            text not null,
  cost_trailer    numeric,
  cost_torton     numeric,
  cost_camion_35  numeric,
  cost_reparto    numeric
);

create table truck_loads (
  id               bigint generated by default as identity primary key,
  created_at       timestamptz not null default now(),
  name             text,
  truck_id         bigint,
  truck_name       text,
  pallet_capacity  integer,
  status           text not null default 'planificando',
  pallets_used     integer,
  destination_id   bigint,
  destination_name text,
  freight_cost     numeric,
  items            jsonb not null default '[]'::jsonb
);
create index on truck_loads (created_at desc);


